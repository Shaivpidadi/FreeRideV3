"""``freeride init`` — interactive setup wizard.

Walks a new user through provider key entry, writes a `.env` file,
optionally prints the next-steps to start the gateway. Goal: cut
onboarding from "read the README, sign up for 6 providers, paste 7
exports into your shell" to one guided command.

Defaults to ``~/.freeride/.env`` for the output, with a clear note
that secrets land on disk there. The destination is ``--out`` if the
user wants something different. Empty input for any provider skips it.

The wizard is non-destructive: never overwrites an existing line for
a provider that the user didn't enter a new value for. Re-running
``freeride init`` after the first time is safe — it just adds new
keys without dropping old ones.
"""

from __future__ import annotations

import webbrowser
from pathlib import Path
from typing import Callable


